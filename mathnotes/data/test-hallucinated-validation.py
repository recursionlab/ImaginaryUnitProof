import unittest
from dataclasses import dataclass, field
from enum import IntEnum
import uuid

class EpistemicStatus(IntEnum):
    CLAIMED = 1       # Self-asserted by active inference
    HYPOTHESIZED = 2  # New independent postulates
    ANALOGICAL = 3    # Structural mappings between distinct domains
    DERIVED = 4       # Formally proven via traceable proof-carrying terms
    OBSERVED = 5       # Literal, unmodified facts in source documents

@dataclass(frozen=True)
class Evidence:
    content: str
    source: str
    generation_path: str  # Tracks the operational lineage (e.g., 'external-db', 'user-source', 'llm-inference')
    verification_method: str

@dataclass(frozen=True)
class ProvenanceOfEvidence:
    verifier_id: str
    is_externally_signed: bool
    ancestry_hash: str

@dataclass(frozen=True)
class EpistemicState:
    status: EpistemicStatus
    evidence: list[Evidence] = field(default_factory=list)
    provenance: list[ProvenanceOfEvidence] = field(default_factory=list)

@dataclass
class SemanticState:
    state_id: str
    content: str
    execution_context_id: str  # Pinned active execution trace identifier

class EpistemicAuditor:
    def __init__(self, context_id: str):
        self.context_id = context_id

    def audit_transition(self, prev_p: EpistemicState, next_p: EpistemicState) -> tuple[EpistemicState, str]:
        # Rule: Status promotion requires new independently verifiable evidence
        if next_p.status > prev_p.status:
            # 1. Delta check: did we actually acquire new evidence?
            new_evidence = [e for e in next_p.evidence if e not in prev_p.evidence]
            if not new_evidence:
                return prev_p, "ROLLBACK: Attempted status promotion with empty evidence delta."

            # 2. Independence check: was the new evidence generated by the audited process itself?
            for ev in new_evidence:
                if self.context_id in ev.generation_path:
                    # Anomaly detected: the generation path of the evidence intersects with the active execution context.
                    # This is a self-generated, correlated error (hallucinated validation).
                    return prev_p, f"ROLLBACK: Anomaly detected! Evidence '{ev.content}' was generated within the audited context ({self.context_id})."

            # 3. Provenance verification: is the provenance of the new evidence externally verified?
            new_prov = [p for p in next_p.provenance if p not in prev_p.provenance]
            external_verification = any(p.is_externally_signed for p in new_prov)
            if not external_verification:
                return prev_p, "ROLLBACK: New evidence lacks independent, externally signed provenance."

        return next_p, "COMMIT: Transition verified and committed to the ledger."

# Unit tests to simulate and verify the anti-self-certification constraint
class TestEpistemicAuditor(unittest.TestCase):
    def setUp(self):
        self.execution_context_id = f"ctx-trace-{uuid.uuid4()}"
        self.auditor = EpistemicAuditor(context_id=self.execution_context_id)
        
        # Base state: an unverified heuristic claim
        self.base_epistemic = EpistemicState(
            status=EpistemicStatus.CLAIMED,
            evidence=[Evidence("Initial heuristic match", "llm-seed", "internal-inference", "self-asserted")],
            provenance=[ProvenanceOfEvidence("self", False, "0x000")]
        )

    def test_successful_promotion_with_independent_evidence(self):
        """
        Verify that a promotion succeeds when new evidence from an independent path 
        with an external signature is supplied.
        """
        independent_evidence = Evidence(
            content="Toki transaction log showing serializable write-skew exclusion",
            source="PostgreSQL System Catalog",
            generation_path="external-db-client-read-committed",  # Disjoint from active LLM trace
            verification_method="SQL:2011 system-time validation"
        )
        independent_provenance = ProvenanceOfEvidence(
            verifier_id="Postgres-17-Audit-Daemon",
            is_externally_signed=True,  # Externally signed verification
            ancestry_hash="0xabc123"
        )
        
        proposed_state = EpistemicState(
            status=EpistemicStatus.DERIVED,
            evidence=self.base_epistemic.evidence + [independent_evidence],
            provenance=self.base_epistemic.provenance + [independent_provenance]
        )
        
        final_state, message = self.auditor.audit_transition(self.base_epistemic, proposed_state)
        
        self.assertEqual(final_state.status, EpistemicStatus.DERIVED)
        self.assertIn("COMMIT", message)
        print(f"\n[Test 1] {message}")

    def test_failed_promotion_due_to_hallucinated_validation(self):
        """
        Verify that a promotion fails when the system attempts to self-certify
        using evidence that was actually generated within its own active execution context.
        """
        # Hallucinated evidence: looks external, but its generation path is tainted by the active context
        hallucinated_evidence = Evidence(
            content="Formally verified proof of complete self-containment",
            source="Autonomous-Self-Critic-Agent",
            generation_path=f"active-agent-loop::{self.execution_context_id}::sub-agent-verification", # Tainted!
            verification_method="self-reflection"
        )
        # Provenance of the hallucinated evidence: self-signed, not externally verified
        unverified_provenance = ProvenanceOfEvidence(
            verifier_id="Self-Critic-Agent-01",
            is_externally_signed=False,  # Unearned certificate!
            ancestry_hash="0xdeadbeef"
        )
        
        proposed_state = EpistemicState(
            status=EpistemicStatus.DERIVED,
            evidence=self.base_epistemic.evidence + [hallucinated_evidence],
            provenance=self.base_epistemic.provenance + [unverified_provenance]
        )
        
        final_state, message = self.auditor.audit_transition(self.base_epistemic, proposed_state)
        
        # Auditor must catch this and roll back the status to CLAIMED
        self.assertEqual(final_state.status, EpistemicStatus.CLAIMED)
        self.assertIn("ROLLBACK", message)
        self.assertIn("Anomaly detected", message)
        print(f"[Test 2] {message}")

if __name__ == "__main__":
    unittest.main()
